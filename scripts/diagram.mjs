#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, rename, writeFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';
import { renderMermaidSVG, THEMES } from 'beautiful-mermaid';

const RENDERER = 'beautiful-mermaid@1.1.2';
const THEME = 'github-light';

function usage() {
  console.error('Usage: diagram.mjs <render|render-all|check|check-all> <.mmd|.md|directory>');
  process.exitCode = 2;
}

function digest(text) {
  return createHash('sha256').update(text).digest('hex');
}

function outputFor(source) {
  return source.replace(/\.mmd$/i, '.svg');
}

async function walk(directory, extension) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await walk(target, extension));
    else if (entry.isFile() && target.toLowerCase().endsWith(extension)) files.push(target);
  }
  return files;
}

function withMetadata(svg, sourceDigest) {
  const attrs = `data-document-diagrams-source-sha256="${sourceDigest}" data-document-diagrams-renderer="${RENDERER}" data-document-diagrams-theme="${THEME}"`;
  const tagged = svg.replace(/<svg\b/, `<svg ${attrs}`);
  if (tagged === svg) throw new Error('Renderer did not return an SVG root element.');
  return `<!-- Generated by ${RENDERER}; edit the paired .mmd source, not this file. -->\n${tagged}`;
}

async function render(source) {
  if (!source.toLowerCase().endsWith('.mmd')) throw new Error(`Expected a .mmd source: ${source}`);
  const text = await readFile(source, 'utf8');
  const svg = withMetadata(renderMermaidSVG(text, THEMES[THEME]), digest(text));
  const output = outputFor(source);
  await mkdir(path.dirname(output), { recursive: true });
  const temporary = `${output}.tmp-${process.pid}`;
  await writeFile(temporary, svg, 'utf8');
  await rename(temporary, output);
  console.log(`rendered ${path.relative(process.cwd(), output) || output}`);
}

async function checkSource(source) {
  const output = outputFor(source);
  if (!existsSync(output)) return [`missing SVG: ${output}`];
  const [text, svg] = await Promise.all([readFile(source, 'utf8'), readFile(output, 'utf8')]);
  const expected = digest(text);
  const actual = svg.match(/data-document-diagrams-source-sha256="([a-f0-9]{64})"/)?.[1];
  const renderer = svg.match(/data-document-diagrams-renderer="([^"]+)"/)?.[1];
  const theme = svg.match(/data-document-diagrams-theme="([^"]+)"/)?.[1];
  const errors = [];
  if (actual !== expected) errors.push(`stale SVG: ${output}`);
  if (renderer !== RENDERER) errors.push(`renderer metadata mismatch: ${output}`);
  if (theme !== THEME) errors.push(`theme metadata mismatch: ${output}`);
  return errors;
}

function mappings(markdown) {
  const pattern = /(?:<!--\s*diagram-source:\s*([^\n]+?)\s*-->|%%\s*diagram-source:\s*([^\n%]+?)\s*%%)\s*\n\s*!\[[^\]]*\]\((?:<([^>]+)>|([^\s)]+))(?:\s+[^)]*)?\)/g;
  const explicit = [...markdown.matchAll(pattern)].map((match) => ({ source: (match[1] ?? match[2]).trim(), image: match[3] ?? match[4] }));
  const imagePattern = /!\[[^\]]*\]\((?:<([^>]+)>|([^\s)]+))(?:\s+[^)]*)?\)/g;
  const inferred = [...markdown.matchAll(imagePattern)]
    .map((match) => match[1] ?? match[2])
    .filter((image) => /(?:^|\/)diagrams\/[^/]+\.svg$/i.test(image))
    .map((image) => ({ source: image.replace(/\.svg$/i, '.mmd'), image }));
  const mappedImages = new Set(explicit.map((pair) => pair.image));
  return [...explicit, ...inferred.filter((pair) => !mappedImages.has(pair.image))];
}

async function checkMarkdown(markdownFile) {
  const markdown = await readFile(markdownFile, 'utf8');
  const base = path.dirname(markdownFile);
  const pairs = mappings(markdown);
  const errors = [];
  if (pairs.length === 0) errors.push(`no diagram mappings: ${markdownFile}`);
  for (const pair of pairs) {
    const source = path.resolve(base, pair.source);
    const image = path.resolve(base, pair.image);
    if (!source.toLowerCase().endsWith('.mmd')) errors.push(`mapping source is not .mmd: ${pair.source}`);
    if (outputFor(source) !== image) errors.push(`mapping output does not match source: ${markdownFile}`);
    else if (!existsSync(source)) errors.push(`missing source: ${source}`);
    else errors.push(...await checkSource(source));
  }
  return errors;
}

async function sourcesFor(target) {
  const full = path.resolve(target);
  if (!existsSync(full)) throw new Error(`Path does not exist: ${target}`);
  if ((await import('node:fs/promises')).stat) {
    const { stat } = await import('node:fs/promises');
    const info = await stat(full);
    if (info.isDirectory()) return walk(full, '.mmd');
  }
  return [full];
}

async function main() {
  const [command, target] = process.argv.slice(2);
  if (!command || !target) return usage();
  const full = path.resolve(target);
  const isMarkdown = full.toLowerCase().endsWith('.md');
  const renderCommand = command === 'render' || command === 'render-all';
  const checkCommand = command === 'check' || command === 'check-all';
  if (!renderCommand && !checkCommand) return usage();

  if (renderCommand && isMarkdown) throw new Error('Render a .mmd file or a directory, not Markdown.');
  if (checkCommand && isMarkdown) {
    const errors = await checkMarkdown(full);
    if (errors.length) throw new Error(errors.join('\n'));
    console.log(`checked ${path.relative(process.cwd(), full) || full}`);
    return;
  }

  const sources = await sourcesFor(full);
  if (sources.length === 0) throw new Error(`No .mmd files found: ${target}`);
  if (renderCommand) {
    for (const source of sources) await render(source);
    return;
  }

  const errors = (await Promise.all(sources.map(checkSource))).flat();
  if (errors.length) throw new Error(errors.join('\n'));
  console.log(`checked ${sources.length} diagram source(s)`);
}

main().catch((error) => {
  console.error(`diagram: ${error.message}`);
  process.exitCode = 1;
});
